"""Inputs of one Isaac closed-loop run (scripts/sim_mission.sh): the navigator cfg, field.yaml, spec.json, run.json.

    python3 -m treemapper_tools.sim_inputs --spec <spec.json> --run-dir <dir> --cfg config/corridor_nav.cfg \
        --strategy corridor [--git-commit H --git-dirty N --detector-model P --timeout S --record-images --record-frames]

Standard library only (it runs on the host, before any container). Isaac-free.

* corridor_nav.cfg = the shipped cfg with the values of ``CFG_OVERRIDES`` replaced in place (the navigator's reader
  rejects duplicate keys, so nothing is appended): ``strategy`` from the CLI and the sim-only ``carrot_lead_s 1.2``
  (the Isaac drone's v_max equals the navigator's max speeds, so the longer lead cannot exceed planned speeds).
* field.yaml has exactly the keys ``ros/corridor_nav_ros/src/field_file.cpp`` accepts: ``polygon`` [[x, y], ...] (>= 3
  vertices, non-zero area), ``heading_rad`` = spec ``rows.heading_rad``, ``home`` = spec ``drone.home``.
"""
import argparse
import json
import math
import os
import sys
import time
from typing import Dict, List, Sequence

SIM_CARROT_LEAD_S = "1.2"
FIELD_KEYS = ("polygon", "heading_rad", "home")


def cfg_overrides(strategy: str) -> Dict[str, str]:
    if strategy not in ("corridor", "field_first"):
        raise ValueError("strategy must be corridor or field_first, got %r" % strategy)
    return {"strategy": strategy, "carrot_lead_s": SIM_CARROT_LEAD_S}


def run_cfg_text(base_text: str, overrides: Dict[str, str]) -> str:
    """``base_text`` with the value of every key in ``overrides`` replaced on its own line; comments kept. Raises
    ValueError when a key is missing from the base or appears twice."""
    seen: Dict[str, int] = {}
    out: List[str] = ["# generated by scripts/sim_mission.sh: config/corridor_nav.cfg with %s"
                      % ", ".join("%s = %s" % kv for kv in sorted(overrides.items()))]
    for line in base_text.splitlines():
        body = line.split("#", 1)[0]
        key = body.split("=", 1)[0].strip() if "=" in body else ""
        if key in overrides:
            seen[key] = seen.get(key, 0) + 1
            out.append("%s = %s" % (key, overrides[key]))
        else:
            out.append(line)
    missing = sorted(set(overrides) - set(seen))
    if missing:
        raise ValueError("base cfg has no key %s" % missing)
    dup = sorted(k for k, n in seen.items() if n > 1)
    if dup:
        raise ValueError("base cfg repeats key %s" % dup)
    return "\n".join(out) + "\n"


def field_yaml_text(spec: dict, source: str = "") -> str:
    poly = [(float(x), float(y)) for x, y in spec["field"]["polygon"]]
    home = [float(v) for v in spec["drone"]["home"]]
    heading = float(spec["rows"]["heading_rad"])
    if len(poly) < 3:
        raise ValueError("field.polygon needs at least 3 vertices")
    twice_area = sum(p[0] * q[1] - q[0] * p[1] for p, q in zip(poly, poly[1:] + poly[:1]))
    if not abs(twice_area) > 1e-9:
        raise ValueError("field.polygon has zero area")
    if len(home) != 2 or not all(math.isfinite(v) for v in home + [heading] + [c for p in poly for c in p]):
        raise ValueError("field polygon, rows.heading_rad and drone.home must be finite, home = [x, y]")
    lines = ["# generated by scripts/sim_mission.sh%s" % (" from " + source if source else ""),
             "polygon: [%s]" % ", ".join("[%r, %r]" % p for p in poly),
             "heading_rad: %r" % heading,
             "home: [%r, %r]" % (home[0], home[1])]
    return "\n".join(lines) + "\n"


def write_run_inputs(spec_path: str, run_dir: str, base_cfg: str, strategy: str, git_commit: str = "",
                     git_dirty: int = 0, detector_model: str = "", timeout: float = 1800.0,
                     record_images: bool = False, record_frames: bool = False) -> dict:
    with open(spec_path) as f:
        spec = json.load(f)
    overrides = cfg_overrides(strategy)
    with open(base_cfg) as f:
        cfg = run_cfg_text(f.read(), overrides)
    field = field_yaml_text(spec, os.path.basename(spec_path))
    with open(os.path.join(run_dir, "spec.json"), "w") as f:
        json.dump(spec, f, indent=1)
    with open(os.path.join(run_dir, "field.yaml"), "w") as f:
        f.write(field)
    with open(os.path.join(run_dir, "corridor_nav.cfg"), "w") as f:
        f.write(cfg)
    run = {"spec": spec, "spec_file": spec_path, "strategy": strategy, "git_commit": git_commit,
           "git_dirty_files": int(git_dirty), "seed": spec.get("seed"), "detector_model": detector_model,
           "timeout_sim_s": float(timeout), "record_images": bool(record_images),
           "record_frames": bool(record_frames),
           "isaac": {"v_max_xy": 4.0, "v_max_z": 1.5, "max_rtf": 1.0}, "cfg_overrides": overrides,
           "started_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    with open(os.path.join(run_dir, "run.json"), "w") as f:
        json.dump(run, f, indent=1)
    return run


def main(argv: Sequence[str] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec", required=True)
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--cfg", required=True, help="base navigator cfg (config/corridor_nav.cfg)")
    ap.add_argument("--strategy", required=True)
    ap.add_argument("--git-commit", default="")
    ap.add_argument("--git-dirty", type=int, default=0)
    ap.add_argument("--detector-model", default="")
    ap.add_argument("--timeout", type=float, default=1800.0)
    ap.add_argument("--record-images", action="store_true")
    ap.add_argument("--record-frames", action="store_true",
                    help="the run records TreeMapper's inputs (disparity, camera_info) for tools/treemapper_tools/sim_frames.py")
    a = ap.parse_args(argv)
    try:
        write_run_inputs(a.spec, a.run_dir, a.cfg, a.strategy, a.git_commit, a.git_dirty, a.detector_model,
                         a.timeout, a.record_images, a.record_frames)
    except (OSError, ValueError, KeyError, TypeError) as e:
        print("sim_inputs: %s" % e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
